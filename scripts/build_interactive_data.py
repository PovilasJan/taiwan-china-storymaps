"""Build a small, offline-capable browser data bundle from the audited source."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PALETTE = ['#b2182b', '#d6604d', '#e8854a', '#f4ac5e', '#f6cf65',
           '#d9df80', '#a7cf6a', '#67ad59', '#25834a']
DOMAINS = ['Ekonomika', 'Švietimas ir technologijos', 'Sveikata ir demografija', 'Ekologija']


def main():
    source = json.loads((ROOT/'data/indicators.json').read_text(encoding='utf-8'))
    selected = []
    for row in source['indicators']:
        item = {key: row[key] for key in ['id', 'domain', 'indicator', 'unit',
                'direction', 'note', 'score_note', 'scores']}
        item['benchmark'] = {key: row['benchmark'][key] for key in
                ['year', 'n', 'min', 'max', 'scope', 'source']}
        for country in ['taiwan', 'china']:
            item[country] = {key: row[country][key] for key in
                    ['value', 'year', 'source', 'source_title'] if key in row[country]}
        selected.append(item)
    bundle = {
        'title': 'Taivano ir Kinijos Darnūs ratai',
        'updated': source['accessed'],
        'method': 'Devyni vienodo pločio atskaitos intervalai',
        'source_url': 'https://www.circlesofsustainability.com/circles-overview/profile-circles/',
        'palette': PALETTE,
        'domains': DOMAINS,
        'indicators': selected,
    }
    target = ROOT/'docs'
    target.mkdir(exist_ok=True)
    (target/'indicators.js').write_text(
        '// Generated by scripts/build_interactive_data.py; edit data/indicators.json instead.\n'
        'window.CIRCLE_DATA = '+json.dumps(bundle, ensure_ascii=False, indent=2)+';\n',
        encoding='utf-8')
    (target/'.nojekyll').touch()
    print(f'Built browser bundle: {len(selected)} indicators, 56 source scores')


if __name__ == '__main__':
    main()
